static bool scan_region(const uint8_t* data, size_t data_len, uint64_t base_va,
                        const KnownConstant& kc, std::vector<CryptoHit>& hits)
{
    if (data_len < kc.min_match) return false;

    bool found = false;
    size_t search_len = data_len - kc.min_match + 1;

    for (size_t i = 0; i < search_len; i++) {
        if (data[i] != kc.data[0]) continue;

        size_t match = 0;
        size_t max_check = std::min(kc.len, data_len - i);
        while (match < max_check && data[i + match] == kc.data[match])
            match++;

        if (match >= kc.min_match) {
            CryptoHit hit;
            hit.addr = base_va + i;
            hit.algorithm = kc.algorithm;
            hit.constant_name = kc.name;
            hit.match_len = match;
            hits.push_back(std::move(hit));
            found = true;
            i += match - 1;
        }
    }
    return found;
}

CryptoScanResult scan_crypto_constants(const BinaryImage& img) {
    CryptoScanResult result;

    for (auto& sec : img.sections) {
        if (sec.file_off + sec.file_size > img.raw.size()) continue;
        const uint8_t* data = img.raw.data() + sec.file_off;
        size_t len = sec.file_size;

        for (size_t c = 0; c < NUM_CONSTANTS; c++) {
            scan_region(data, len, sec.vaddr, g_known_constants[c], result.hits);
        }
    }

    std::sort(result.hits.begin(), result.hits.end(),
              [](const CryptoHit& a, const CryptoHit& b) { return a.addr < b.addr; });

    return result;
}

